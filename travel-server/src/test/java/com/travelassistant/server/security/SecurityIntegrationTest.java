package com.travelassistant.server.security;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.mock.web.MockHttpSession;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest
@AutoConfigureMockMvc
class SecurityIntegrationTest {

  @Autowired
  private MockMvc mvc;

  @Autowired
  private ObjectMapper objectMapper;

  /** 把账号落盘到测试专用目录，避免污染 data/ 与跨测试互相影响。 */
  @DynamicPropertySource
  static void props(org.springframework.test.context.DynamicPropertyRegistry registry) {
    registry.add("travel.data-directory", () -> "target/security-test-data");
  }

  @Test
  void healthEndpointIsPublic() throws Exception {
    mvc.perform(get("/api/health")).andExpect(status().isOk());
  }

  @Test
  void registerLoginSessionMeLogoutFlow() throws Exception {
    String username = "alice_" + System.nanoTime();
    String password = "password123";

    // 1) 注册 -> 201，账号写入服务端 JSON
    mvc.perform(post("/api/account/register")
            .contentType("application/json")
            .content(objectMapper.writeValueAsString(Map.of("username", username, "password", password))))
        .andExpect(status().isCreated())
        .andExpect(jsonPath("$.username").value(username));

    // 2) 登录 -> 200，服务端建立会话并下发 JSESSIONID Cookie
    MockHttpSession session = new MockHttpSession();
    mvc.perform(post("/api/login").param("username", username).param("password", password).session(session))
        .andExpect(status().isOk())
        .andExpect(jsonPath("$.authenticated").value(true));

    // 3) 携带会话访问受保护资源 -> 200，能识别当前用户
    mvc.perform(get("/api/account/me").session(session))
        .andExpect(status().isOk())
        .andExpect(jsonPath("$.username").value(username));

    // 4) 退出 -> 200，会话失效
    mvc.perform(post("/api/logout").session(session)).andExpect(status().isOk());

    // 5) 退出后原会话不再有效 -> 401
    mvc.perform(get("/api/account/me").session(new MockHttpSession())).andExpect(status().isUnauthorized());
  }

  @Test
  void defaultAutoGeneratedUserIsReplaced() throws Exception {
    // 不应再存在启动时打印随机密码的默认 user 账号
    mvc.perform(post("/api/login").param("username", "user").param("password", "whatever"))
        .andExpect(status().isUnauthorized());
  }

  @Test
  void duplicateRegistrationReturnsConflict() throws Exception {
    String username = "bob_" + System.nanoTime();
    String body = objectMapper.writeValueAsString(Map.of("username", username, "password", "password123"));
    mvc.perform(post("/api/account/register").contentType("application/json").content(body))
        .andExpect(status().isCreated());
    mvc.perform(post("/api/account/register").contentType("application/json").content(body))
        .andExpect(status().isConflict());
  }

  @Test
  void weakPasswordIsRejected() throws Exception {
    mvc.perform(post("/api/account/register")
            .contentType("application/json")
            .content(objectMapper.writeValueAsString(Map.of("username", "carol", "password", "123"))))
        .andExpect(status().isBadRequest());
  }
}
