/// 从一句话里认出最长的已知地名；认不出返回 null。
String? guessPlace(String text) {
  final t = text.trim();
  if (t.isEmpty) return null;
  String? best;
  for (final p in kKnownPlaces) {
    if (t.contains(p) && (best == null || p.length > best.length)) {
      best = p;
    }
  }
  return best;
}

/// 从一句话里认出天数：「3 天」「三天」「两日」。
int? guessDays(String text) {
  final m = RegExp(r'(\d{1,2})\s*[天日]').firstMatch(text);
  if (m != null) {
    final n = int.tryParse(m.group(1)!);
    if (n != null && n >= 1 && n <= 30) return n;
  }
  const cn = {'一': 1, '两': 2, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7};
  final m2 = RegExp(r'([一两二三四五六七])\s*[天日]').firstMatch(text);
  if (m2 != null) return cn[m2.group(1)];
  return null;
}
